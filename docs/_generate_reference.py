REFERENCE_YAML = ROOT / "examples" / "reference.yaml"
_REFERENCE_HEADER = """\
# soma reference configuration: every section of soma.ExperimentConfig, each field at
# its default. Generated by docs/_generate_reference.py; do not edit by hand.
#
# A config names its own records, splits, encoder and learner; everything else may be
# left out. Leaf params ({name, params}) are each component's own: `soma list KIND`
# prints them with their defaults, and a run's plan.yaml records every value it used.
# features.execution.num_gpus and num_preprocessing_workers are null here: slide2vec
# resolves them for the machine a run starts on.
# Run with: soma run /path/to/config.yaml
"""


def reference_config() -> ExperimentConfig:
    """The reference experiment: a slide-level MIL classifier, every other field default."""
    return ExperimentConfig(
        cohort=CohortConfig(records="data/dataset.csv", splits="data/splits.csv"),
        features=FeaturesConfig(encoder="uni2"),
        learner=LearnerConfig("mil", {"aggregator": "abmil", "head": "binary_classification"}),
    )


def _reference_config_yaml() -> str:
    """The reference experiment as YAML."""
    return yaml.safe_dump(reference_config().to_dict(), sort_keys=False, default_flow_style=False)


def build_reference_yaml() -> str:
    """``examples/reference.yaml``: the reference experiment as YAML, under a header."""
    return _REFERENCE_HEADER + "\n" + _reference_config_yaml()


def _default_config_yaml_block() -> str:
    """The reference experiment's YAML as an indented RST code block body."""
    return indent(_reference_config_yaml().strip(), "   ")


def _benchmark_family(family: str) -> list:
    """The registered members ``family/<dataset>`` of a benchmark family, sorted by name."""
    return [get_benchmark(entry["name"]) for entry in components("benchmarks") if entry["name"].startswith(f"{family}/")]


def _preset_rows() -> str:
    """One bullet per registered preset: its call signature and its summary line."""
    lines = []
    for entry in components("presets"):
        arguments = ", ".join(
            name if name in entry["required"] else f'{name}="{value}"' if isinstance(value, str) else f"{name}={value!r}"
            for name, value in entry["params"].items()
        )
        lines.append(f"* ``{entry['name']}({arguments})`` — {entry['description']}")
    return "\n".join(lines)


def build_cli_rst() -> str:
    config_reference = _default_config_yaml_block()
    kinds = ", ".join(f"``{kind}``" for kind in components())
    body = (
        dedent(
        """\
        CLI
        ===

        Use ``soma`` to run experiments, discover components, score
        predictions, reproduce benchmarks, and compare completed runs.

        .. figure:: /_static/figures/run-flow.svg
           :figclass: soma-figure
           :alt: Three input files flow into one soma command that schedules tiling, feature extraction, training, and metrics.

           You provide three files — a dataset, splits, and a config. ``soma`` then
           schedules every step: tiling, feature extraction, training, and metrics.

        Basic usage
        -----------

        ``soma run`` runs a YAML config::

            soma run /path/to/config.yaml

        or a preset on your cohort (see :ref:`presets`)::

            soma run --preset mil_classification --encoder uni2 --aggregator abmil \\
                --cohort dataset.csv --splits splits.csv --out runs

        A config is edited, not overridden: there are no override flags. To start
        from a preset and change it, print it as YAML with every default filled in,
        edit the file, and run it::

            soma init mil_classification --encoder uni2 --aggregator abmil > experiment.yaml
            soma run experiment.yaml

        Use ``soma --help`` or ``soma COMMAND --help`` for command options.

        Train on features you already have with ``--feature-dir``: the directory of a
        pooled feature cache (slide, patient and tile runs) or of dense grids
        (segmentation and detection). The run attaches it and extracts nothing::

            soma run config.yaml --feature-dir runs/features/uni2

        ``soma`` prints soma's INFO log messages to stderr, and warnings and errors
        from other libraries. See :ref:`log-output` for the same behaviour in a Python
        script.

        Available commands
        ------------------

        ``soma run CONFIG [--feature-dir DIR]``
           Run an experiment from a YAML config file, optionally on pre-extracted
           features. The run directory keeps the config as given (``config.yaml``)
           and its resolved plan (``plan.yaml``), written before training starts;
           ``soma run plan.yaml`` replays a run with every value pinned.

        ``soma run --preset NAME --cohort CSV --splits CSV --out DIR [--seed N] [PRESET ARGUMENTS] [--feature-dir DIR]``
           Run a preset on a cohort: the preset's own arguments are flags
           (``--encoder``, ``--aggregator``, ``--decoder``; ``soma run --preset NAME
           --help`` lists them), its required ones are required, and ``--seed``
           defaults to 0. The registered presets:

        __PRESETS__

        ``soma init NAME [PRESET ARGUMENTS]``
           Print the preset as an editable YAML config with every component's
           params at their defaults. Fields the cohort or the machine decide are
           ``null``; point ``cohort.records`` and ``cohort.splits`` at your files
           before ``soma run``.

        ``soma list [KIND] [--level {tile,slide,patient}]``
           Without ``KIND``, list the component kinds: __KINDS__.
           With a ``KIND``, list its registered components and the default of
           each of their params; ``soma list benchmarks`` prints the names
           ``soma reproduce`` and ``soma leaderboard`` accept. ``--level``
           narrows the encoders to ``tile``, ``slide``, or ``patient``.
           :func:`soma.components` returns the same listing in Python.

        ``soma evaluate PREDICTIONS --cohort CSV [--splits CSV --split NAME --fold N] [--metrics M ...] [--subgroups COL ...] [--out JSON]``
           Score saved predictions against the targets in ``dataset.csv``,
           joined by ``sample_id``; no run directory is needed. ``PREDICTIONS``
           is a predictions parquet, a points parquet (detection), or a
           label-map directory (segmentation). A predictions parquet is scored
           against the cohort's target columns, points against the files in its
           ``points_path`` column, and label maps against the class-index masks
           in its ``label_mask_path`` column. ``--splits``
           selects one split (default ``test``) of one fold (default ``0``);
           without it every row of the cohort is a target. Every prediction
           needs a target and every target a prediction. ``--metrics`` takes
           metric names or dotted import paths (default: the task family's
           defaults); ``--subgroups`` names metadata columns to break the
           metrics down by. The metrics table is printed; ``--out`` also writes
           the evaluation as JSON. See :doc:`evaluation`.

        ``soma compact-index OUTPUT_ROOT``
           Compact ``indexes/runs.csv`` to the latest row per run. Readers
           already deduplicate the append-only index; compaction saves space.
           A path to the CSV itself is also accepted. See :doc:`outputs`.

        Benchmarking commands
        ---------------------

        ``soma prepare-croma RAW_ROOT [--rebuild]``
           Download and decode the pinned PathoROB tile sources for
           :doc:`croma-robustness-benchmark`. ``--rebuild`` replaces a partial
           or revision-mismatched destination.

        ``soma reproduce NAME [--encoder NAME | --encoders NAME [NAME ...]] [--raw-root DIR | --curated-dir DIR | --from-run-dir DIR] [--seeds N] [--devices LIST]``
           Curate, run, and score a registered benchmark. ``NAME`` is a benchmark
           (``ocelot``, ``eva/bach``) or a family prefix (``eva``). ``--raw-root``
           curates from raw data, ``--curated-dir`` reuses prepared manifests, and
           ``--from-run-dir`` rescores one existing run. ``--encoders`` runs an
           ordered panel and writes one leaderboard per benchmark. ``--seeds N``
           runs seeds 0 through N−1. ``--devices 0,1,2,3`` runs the seeds side by
           side, one process per GPU (``cpu`` entries run on the CPU). ``--output-root``,
           ``--cache-root``, and ``--out-dir`` place run artifacts, shared features,
           and curated manifests; ``--record`` appends the score to the benchmark's
           results ledger, ``soma/benchmark/<protocol>/results.csv`` next to its
           ``reference.csv``. See :doc:`benchmarking` for panel validation,
           partial failures, parallel seeds, and reference comparisons.

        ``soma leaderboard [NAME] --root OUTPUT_ROOT [--vary AXIS] [--fix AXIS=VALUE] [--like DIR]``
           Render a faceted leaderboard over the completed run dirs under an
           output root. A benchmark ``NAME`` supplies the canonical facet and
           reference band; ``--vary`` / ``--fix`` / ``--like`` shape the facet on
           top of it.

        Full config reference
        ---------------------

        A config has seven sections, one per public callable: ``run`` holds
        :class:`~soma.pipeline.Pipeline`'s keywords, ``cohort`` the cohort's,
        ``features`` the feature source's, ``loaders`` the data loaders', ``learner``
        the learner's, ``trainer`` the :class:`~soma.learn.Trainer`'s and
        ``evaluation`` :func:`~soma.evaluate`'s. The YAML below is
        ``examples/reference.yaml``: a slide-level classifier with every other field
        at its default. A config states only what differs; :func:`soma.resolve` fills
        in the rest and writes it to the run's ``plan.yaml``. Component params
        (``{name, params}``) are listed by ``soma list KIND``. See
        :doc:`configuration`.

        .. code-block:: yaml

        """
        )
        .replace("__KINDS__", kinds)
        .replace("__PRESETS__", indent(_preset_rows(), "   "))
        + config_reference
        + "\n\n"
        + dedent(
            """\
        See also
        --------

        * :doc:`api` — Python interfaces and recipes.
        * :doc:`modeling` — supported component combinations.

        """
        )
    )
    return body.rstrip() + "\n"


def write_reference_yaml(path: str | Path | None = None) -> Path:
    """Write ``examples/reference.yaml``."""
    target = Path(path) if path is not None else REFERENCE_YAML
    target.write_text(build_reference_yaml(), encoding="utf-8")
    return target


def write_cli_rst(path: str | Path | None = None) -> Path:
    """Write the generated CLI guide page to disk."""

    target = Path(path) if path is not None else Path(__file__).with_name("cli.rst")
    target.write_text(build_cli_rst(), encoding="utf-8")
    return target


# --- benchmark pages (generated from the registered Benchmark definitions) -----------
#
# Each per-benchmark page is generated from its registered ``Benchmark`` object: the
# protocol summary comes from ``facet`` / ``primary_metric`` / ``canonical_seeds`` /
# ``reference_environment``, the reproduce command from ``benchmark.name``, and the
# reference numbers are read from the benchmark's ``expected()`` reference rows (packaged
# ``soma/benchmark/<name>/reference.csv``) and rendered as a readable ``list-table`` — the
# gate band beside the measured cells, a linked source instead of dumping the CSV's verbose
# ``source`` column (no hand-typed numbers, no drift, no ``TBD``). A generator + a
# checked-in file kept in sync by ``tests/repo/test_docs.py`` mirrors the ``cli.rst`` mechanism.

# Maintainers: the benchmark pages (``docs/*-benchmark.rst``) are written by hand; only their
# results tables are generated here, from ``soma/benchmark/<name>/results.csv`` (the ledger
# ``soma reproduce --record`` appends to) and ``reference.csv``. Regenerate them with
# ``python docs/_generate_reference.py``; ``tests/repo/test_docs.py`` checks parity.

def _latest_rows(rows, *, key_columns=None):
    """The most recent ledger row per (key, metric) cell, in first-seen cell order.

    The results ledger is append-only, so a cell reproduced at a new commit adds a row
    rather than rewriting history; the docs show the latest reproduction of each cell
    (``reproduced_rows`` documents "take the last match"). ``key_columns`` selects
    the displayed axes when fixed metadata differs between historical and recorder rows.
    """
    latest: dict[tuple, object] = {}
    for row in rows:
        key = (
            tuple(sorted(row.key.items())) if key_columns is None
            else tuple((column, row.key.get(column, "")) for column in key_columns)
        )
        latest[(key, row.metric)] = row
    return list(latest.values())


_RED_ROLE = (
    ".. raw:: html\n\n"
    "   <style>.red { color: #d32f2f; font-weight: 600; }</style>\n\n"
    ".. role:: red"
)


def _flag(value: float, text: str, gate) -> str:
    """Wrap ``text`` in the ``:red:`` role when ``value`` falls outside ``gate``'s band."""
    if gate is not None and not gate.within_tolerance(value):
        return f":red:`{text}`"
    return text


def _results_table(
    name: str,
    key_columns: tuple[str, ...],
    key_labels: tuple[str, ...],
    metric_label: str,
    *,
    metric: str | None = None,
    std_label: str = "std",
    reproduce_command: str | None = None,
    check_reference: bool = True,
    reference_axes: dict[str, str] | None = None,
) -> str:
    """A ``list-table`` of soma's recorded scores, best first.

    Built from the packaged results ledger (``<name>/results.csv``): only cells that have
    been run appear, latest row per cell. A score outside its gate's band is red; the
    gate itself is not a column, since these benchmarks are soma's own.
    """
    rows = [
        row for row in _latest_rows(load_results(name), key_columns=key_columns)
        if metric is None or row.metric == metric
    ]
    if not rows:
        return (
            f"No reproductions have been recorded yet. ``soma reproduce {reproduce_command or name} --record`` "
            "appends a measured score to the results ledger this table reads."
        )
    header = list(key_labels) + [f"{metric_label} (mean ± {std_label})", "Seeds"]
    lines = [".. list-table::", "   :header-rows: 1", ""]
    lines.extend([f"   * - {header[0]}"] + [f"     - {col}" for col in header[1:]])
    flagged = False
    for row in sorted(rows, key=lambda r: -r.measured):
        measured = f"{row.measured:.3f}" + (f" ± {row.std:.3f}" if row.std is not None else "")
        seeds = "" if row.n_seeds is None else str(row.n_seeds)
        gates = [
            g
            for g in (
                expected_rows(name, metric=row.metric, **{**(reference_axes or {}), **row.key})
                if check_reference else []
            )
            if not g.is_external
        ]
        gate = gates[0] if gates else None
        if gate is not None and not gate.within_tolerance(row.measured):
            flagged = True
        measured = _flag(row.measured, measured, gate)
        cells = [row.key.get(c, "") for c in key_columns] + [measured, seeds]
        lines.extend([f"   * - {cells[0]}"] + [f"     - {cell}" for cell in cells[1:]])
    table = "\n".join(lines)
    return _RED_ROLE + "\n\n" + table if flagged else table


def build_ocelot_results_rst() -> str:
    """The OCELOT results table: one row per recorded encoder."""
    return _results_table("ocelot", ("encoder",), ("Encoder",), "Mean F1")


def build_midog_results_rst() -> str:
    """The MIDOG results table: one row per recorded encoder."""
    # Its packaged target is seed 0; the aggregate table cannot evaluate that check.
    return _results_table(
        "midog", ("encoder",), ("Encoder",), "Stitched-ROI F1",
        metric="f1", std_label="seed std", reproduce_command="detection/midog",
        check_reference=False,
    )


def build_monkey_results_rst() -> str:
    """The MONKEY results table: one row per recorded encoder."""
    return _results_table(
        "monkey", ("encoder",), ("Encoder",), "Inflammatory FROC",
        metric="froc_inflammatory", std_label="seed std", reproduce_command="detection/monkey --seeds 1",
        # The recorder emits only the varying encoder axis for this fixed recipe.
        reference_axes={"dataset": "monkey", "spacing": "0.242"},
    )


def _eva_results_table(datasets, metric: str, reference_label: str, example: str) -> str:
    """One EVA group's table (dataset, encoder, soma, reference), or the fallback sentence."""
    rows = [
        r
        for r in _latest_rows(load_results("eva"))
        if r.metric == metric and r.key.get("dataset") in datasets
    ]
    if not rows:
        return (
            f"No scores have been recorded yet. ``soma reproduce {example} --encoder "
            f"virchow2 --raw-root /path/to/{example} --record`` records one next to the "
            "published EVA reference."
        )
    lines = [
        ".. list-table::",
        "   :header-rows: 1",
        "",
        "   * - Dataset",
        "     - Encoder",
        f"     - {reference_label} (mean ± std)",
        "     - EVA reference",
    ]
    flagged = False
    # Order by (dataset, encoder) so the table never depends on the ledger's insertion order.
    for row in sorted(rows, key=lambda r: (r.key.get("dataset", ""), r.key.get("encoder", ""))):
        measured = f"{row.measured:.3f}" + (f" ± {row.std:.3f}" if row.std is not None else "")
        gates = [
            g
            for g in expected_rows("eva", metric=row.metric, **row.key)
            if not g.is_external
        ]
        gate = gates[0] if gates else None
        if gate is not None and not gate.within_tolerance(row.measured):
            flagged = True
        lines.extend(
            [
                f"   * - {row.key.get('dataset', '')}",
                f"     - {row.key.get('encoder', '')}",
                f"     - {_flag(row.measured, measured, gate)}",
                f"     - {gate.expected:.3f}" if gate else "     - —",
            ]
        )
    table = "\n".join(lines)
    return _RED_ROLE + "\n\n" + table if flagged else table


